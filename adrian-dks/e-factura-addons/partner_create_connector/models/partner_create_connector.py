class PartnerCreateConnector(models.Model):
    _name = "partner.create.connector"
    _description = "Partner Create from API"

    container_id = fields.Many2one("partner.create.container", help=_("Correlation with partner.create.container"))
    name = fields.Char(string=_("Name"))
    model = fields.Char(string=_("Model"))
    endpoint = fields.Char(string=_("Endpoint"))
    method = fields.Selection(selection=[("get", _("Get")), ("post", _("Post")),
                                         ("delete", _("Delete")), ("put", _("Update"))])
    timeout = fields.Integer(string=_("Timeout"), help=_("Timeout in seconds until the request stops waiting response"))
